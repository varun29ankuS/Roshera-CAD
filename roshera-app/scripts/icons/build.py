"""Build Roshera's icon set.

    python scripts/icons/build.py [--only name,name] [--sizes 16,24,32,48,64]

Renders every scene in scenes.TOOLS and scenes.GLYPHS at each size into
public/icons/<family>/<name>-<size>.png, writes the typed manifest
src/components/ui/icon-manifest.ts, and a contact sheet
scripts/icons/contact-sheet.png for review. Requires numpy.
"""
import argparse
import os
import struct
import sys
import zlib

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from render import render  # noqa: E402
from scenes import GLYPHS, TOOLS  # noqa: E402

APP = os.path.dirname(os.path.dirname(HERE))
SIZES = [16, 24, 32, 48, 64]


def write_png(path, rgba):
    h, w, _ = rgba.shape
    b = (np.clip(rgba, 0, 1) * 255 + 0.5).astype(np.uint8)
    raw = b"".join(b"\x00" + b[y].tobytes() for y in range(h))

    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    with open(path, "wb") as fh:
        fh.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
                 + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def contact_sheet(images, path, per_row=14, bg=(0.96, 0.96, 0.97)):
    tiles = []
    for img in images:
        rgb = img[..., :3] * img[..., 3:] + np.array(bg) * (1 - img[..., 3:])
        t = np.ones((img.shape[0] + 8, img.shape[1] + 8, 3)) * np.array(bg)
        t[4:-4, 4:-4] = rgb
        t[4, 4:-4] = t[-5, 4:-4] = t[4:-4, 4] = t[4:-4, -5] = (0.8, 0.8, 0.84)
        tiles.append(t)
    rows = []
    for i in range(0, len(tiles), per_row):
        row = tiles[i:i + per_row]
        row += [np.ones_like(tiles[0]) * np.array(bg)] * (per_row - len(row))
        rows.append(np.concatenate(row, 1))
    sheet = np.concatenate(rows, 0)
    write_png(path, np.concatenate([sheet, np.ones(sheet.shape[:2] + (1,))], -1))


def edge_gap(img):
    ys, xs = np.nonzero(img[..., 3] > 0.02)
    n = img.shape[0]
    return int(min(xs.min(), ys.min(), n - 1 - xs.max(), n - 1 - ys.max()))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    ap.add_argument("--sizes", default=",".join(map(str, SIZES)))
    args = ap.parse_args()
    only = {s for s in args.only.split(",") if s}
    sizes = [int(s) for s in args.sizes.split(",")]
    families = {"tools": TOOLS, "ui": GLYPHS}
    sheet, problems = [], []
    for family, table in families.items():
        out = os.path.join(APP, "public", "icons", family)
        os.makedirs(out, exist_ok=True)
        for name, make in table.items():
            if only and name not in only:
                continue
            scene = make()
            for n in sizes:
                img = render(scene, n)
                write_png(os.path.join(out, f"{name}-{n}.png"), img)
                if edge_gap(img) < 1:
                    problems.append(f"{family}/{name}-{n}: touches the tile edge")
                if n == 48:
                    sheet.append(img)
            print(f"{family}/{name}", flush=True)
    if sheet:
        contact_sheet(sheet, os.path.join(HERE, "contact-sheet.png"))
    # The manifest lists every scene, whatever subset was rendered this run.
    write_manifest(families, SIZES)
    if problems:
        print("\n".join(problems))
        sys.exit(1)


def write_manifest(families, sizes):
    lines = [
        "// Generated by scripts/icons/build.py -- do not edit by hand.",
        "// Every icon is rendered natively at each size in ICON_SIZES.",
        f"export const ICON_SIZES = [{', '.join(map(str, sizes))}] as const",
        "",
    ]
    for family, table in families.items():
        type_name = "ToolIconName" if family == "tools" else "UiIconName"
        names = " | ".join(f"'{n}'" for n in table)
        lines.append(f"export type {type_name} = {names}")
        const = "TOOL_ICON_NAMES" if family == "tools" else "UI_ICON_NAMES"
        lines.append(f"export const {const}: readonly {type_name}[] = [{', '.join(repr(n) for n in table)}]")
        lines.append("")
    with open(os.path.join(APP, "src", "components", "ui", "icon-manifest.ts"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines).replace('"', "'"))


if __name__ == "__main__":
    main()
